/// Represents the content of a coordinate on the Go board.
/// </summary>
public enum Content
{
  /// <summary>
  /// The coordinate is empty.
  /// </summary>
  Empty,

  /// <summary>
  /// The coordinate has a black stone.
  /// </summary>
  Black,

  /// <summary>
  /// The coordinate has a white stone.
  /// </summary>
  White,
}
